import { writeFileSync } from "node:fs";
import { describe, expect, it } from "vitest";
import { DAILY } from "../src/game/extras";
import { CAMPAIGN } from "../src/game/levels";
import { diagnose, solve } from "./solver";

const solving = process.env.SOLVE === "1";

describe.skipIf(!solving)("solve campaign", () => {
  it(
    "finds a fair script for every authored room",
    () => {
      const solved: Record<string, number[]> = {};
      const missing: string[] = [];
      for (const level of [...CAMPAIGN, ...DAILY]) {
        const times = solve(level);
        if (!times) {
          missing.push(level.id);
          console.log(diagnose(level));
        } else {
          solved[level.id] = times;
          console.log(`${level.id}  ${times.length ? times.join(", ") : "hold"}`);
        }
      }
      writeFileSync(
        new URL("./solutions.ts", import.meta.url),
        `/** Generated by SOLVE=1 npm run solve. Replays are the test, not a hint in the game. */\nexport const SOLUTIONS: Record<string, number[]> = ${JSON.stringify(solved, null, 2)};\n`,
      );
      expect(missing, missing.join(", ")).toEqual([]);
    },
    180_000,
  );
});
