export function campaignLevel(id: string): LevelDef | undefined {
  return CAMPAIGN.find((level) => level.id === id);
}

export function worldLevels(world: number): LevelDef[] {
  return CAMPAIGN.filter((level) => level.world === world);
}

export function unlockedCores(cleared: readonly string[]): ArchetypeId[] {
  const count = (world: number) =>
    CAMPAIGN.filter((level) => level.world === world && cleared.includes(level.id)).length;
  const cores: ArchetypeId[] = ["probe"];
  if (count(1) >= 6) cores.push("wisp");
  if (count(2) >= 6) cores.push("slug");
  if (count(3) >= 6) cores.push("reed");
  return cores;
}
